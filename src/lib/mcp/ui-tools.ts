// MCP tools for Zentico UI: the user's Dashboard as files in their Drive folder `Zentico UI/`
// (see src/lib/ui/*). Agents read the guide, edit the files, validate and reload. Edits only touch
// the user's own UI and are undoable from the Dashboard, so they are `selfService` (no in-call /
// in-dashboard confirmation). Paths are restricted to the folder's layout (UI_PATH).
import { publish } from "../dashboard/store";
import { buildGuide } from "../ui/guide";
import {
  APP_TARGETS,
  COMPONENTS,
  formatErrors,
  ICON_NAMES,
  isUiPath,
  MOD_ACTIONS,
  MOD_EVENTS,
  MOD_QUERIES,
  PERMISSION_DOCS,
  summarizeUi,
  UI_FOLDER,
  utf8Bytes,
  type UiError,
} from "../ui/schema";
import { applyTemplate, makeApp, readUiFiles, syncUi, UiServiceError, writeUiFiles } from "../ui/service";
import { catalog } from "../ui/starter";
import { bool, int, str, ToolError, type Args } from "./args";
import { applyEdits, parseEdits } from "./drive-tools";
import { appUrl, B, I, S, type Tool, type ToolContext } from "./kit";

const MAX_FILE_BYTES = 400 * 1024;
const PATH_PROP = S('Path inside "Zentico UI/": ui.json, theme.json, keys.json, AGENTS.md or mods/<id>/<file> (.json, .html, .css, .js, .md, .txt).');

function pathArg(args: Args): string {
  const p = str(args, "path", { required: true, max: 120 }).trim().replace(/^\.?\/+/, "").replace(/^Zentico UI\//i, "");
  if (!isUiPath(p)) throw new ToolError(`"${p}" is not a valid Zentico UI path (ui.json, theme.json, keys.json, AGENTS.md or mods/<id>/<file>.(json|html|css|js|md|txt); mod ids are lowercase letters, digits and -)`);
  return p;
}

const localeOf = (args: Args) => (str(args, "locale", { max: 5 }) === "en" ? "en" : "es");

function checkResult(errors: UiError[]) {
  return errors.length
    ? { ok: false, errorCount: errors.length, errors: formatErrors(errors), details: errors, hint: "Fix the files and run ui_check again. The user keeps seeing the last valid UI meanwhile." }
    : { ok: true, errorCount: 0 };
}

async function run<T>(fn: () => Promise<T>): Promise<T> {
  try {
    return await fn();
  } catch (e) {
    if (e instanceof UiServiceError) throw new ToolError(e.errors.length ? `${e.message}:\n${formatErrors(e.errors)}` : e.message);
    throw e;
  }
}

const folderUrl = (id: string | null) => (id ? `${appUrl()}/drive?folder=${encodeURIComponent(id)}` : null);

async function write(ctx: ToolContext, path: string, content: string) {
  if (utf8Bytes(content) > MAX_FILE_BYTES) throw new ToolError(`Content is larger than ${MAX_FILE_BYTES / 1024} KB`);
  if (path === "AGENTS.md") throw new ToolError("AGENTS.md is generated by Zentico; don't edit it");
  const { check } = await run(() => writeUiFiles(ctx.session, { [path]: content }, { reason: `agent ${path}` }));
  return { written: path, ...checkResult(check.errors) };
}

