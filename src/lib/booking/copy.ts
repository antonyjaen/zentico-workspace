export type CopyKey = keyof typeof en;
export const COPY = { en, es } as const;

/** Copy in `locale` with {placeholders} filled (values are plain text; callers escape per context). */
export const tr = (locale: "es" | "en", key: CopyKey, vars: Record<string, string> = {}) =>
  COPY[locale][key].replace(/\{(\w+)\}/g, (_: string, k: string) => vars[k] ?? "");
